SECTIONS = ("主诉|现病史|既往史|个人史|婚育史|月经史|家族史|过敏史|体格检查|专科检查|"
            "辅助检查|实验室检查|影像学检查|初步诊断|入院诊断|鉴别诊断|鉴别依据|诊断|处理|治疗方案|病程记录")
SEC_RE = re.compile(r"(?:^|[\n。；;])\s*(%s)\s*(?:[:：]|(?=\n))" % SECTIONS)
DIAG_SECS = ("初步诊断", "入院诊断", "诊断", "鉴别诊断")

CLAUSE = "。；;\n,，：:"
NEG = re.compile(r"(无|未|未见|未及|未触及|未闻及|否认|不伴|没有|未出现|未诉|不存在|可排除|已排除|排除|阴性)[^，。；;\n]{0,4}$")
MINUS = r"[-−–—﹣－]"
NEG_TAIL = re.compile(r"^[^，。；;\n]{0,6}(阴性|\(\s*%s\s*\)|（\s*%s\s*）)" % (MINUS, MINUS))
UNDOC = re.compile(r"(未查|未行|未做|未测|未检|未记录|未提供|未完善|待查|待完善|不详|未回报|拒查)[^，。；;\n]{0,6}$")
FW = str.maketrans({"＞": ">", "＜": "<", "％": "%", "＋": "+", "－": "-", "／": "/",
                    "０": "0", "１": "1", "２": "2", "３": "3", "４": "4", "５": "5",
                    "６": "6", "７": "7", "８": "8", "９": "9"})


def normalize(t):
    t = t.replace("\r\n", "\n").replace("\r", "\n").replace("\u3000", " ").translate(FW)
    return "\n".join(re.sub(r"[ \t\u00a0]+", " ", x).strip() for x in t.split("\n"))


def section_marks(t):
    return list(SEC_RE.finditer(t))


def mask_diag(t):
    marks = section_marks(t)
    if not marks:
        return t
    chars = list(t)
    for i, m in enumerate(marks):
        if m.group(1) not in DIAG_SECS:
            continue
        end = marks[i + 1].start() if i + 1 < len(marks) else len(t)
        for j in range(m.end(), end):
            if chars[j] != "\n":
                chars[j] = "※"
    return "".join(chars)


def sections(t):
    marks = section_marks(t)
    out = {}
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(t)
        body = t[m.end():end].strip(" :：\n;；")
        out[m.group(1)] = (out.get(m.group(1), "") + "\n" + body).strip() if m.group(1) in out else body
    return out


def clause(t, s, e):
    a = s
    while a > 0 and t[a - 1] not in CLAUSE:
        a -= 1
    b = e
    while b < len(t) and t[b] not in CLAUSE:
        b += 1
    return a, b


def verdict(t, s, e):
    a, b = clause(t, s, e)
    pre, suf = t[a:s], t[e:b]
    if UNDOC.search(pre) or UNDOC.search(suf[:12]):
        return "undoc"
    if NEG.search(pre) or NEG_TAIL.search(suf):
        return "neg"
    return "pos"


def snip(origin, s, e, pad=8):
    a, b = max(0, s - pad), min(len(origin), e + pad)
    x = re.sub(r"\s+", " ", origin[a:b]).strip()
    return ("…" if a else "") + (x[:60] + "…" if len(x) > 60 else x) + ("…" if b < len(origin) else "")


def hit(text, pats, origin, neg_pats=()):
    """返回 (状态, 证据)。neg_pats 命中的区间会覆盖同位置的阳性匹配
    （解决"阑尾未见增粗"被当成"阑尾增粗"这类句内否定）。"""
    neg_spans = [(m.start(), m.end()) for p in neg_pats for m in re.finditer(p, text)]
    pos, neg = [], list(neg_spans)
    for p in pats:
        for m in re.finditer(p, text):
            if any(m.start() < e and s < m.end() for s, e in neg_spans):
                continue
            v = verdict(text, m.start(), m.end())
            if v == "pos":
                pos.append((m.start(), m.end()))
            elif v == "neg":
                neg.append((m.start(), m.end()))
    if pos:
        return "pos", [snip(origin, s, e) for s, e in pos[:3]]
    if neg:
        return "neg", [snip(origin, s, e) for s, e in neg[:3]]
    return "missing", []


def eval_core(text, d, origin, exam=None):
    rows = []
    for pt in d["pts"]:
        # 体征类只在查体段里找，避免"既往做过疝手术"被当成"查体见包块"
        body = exam if (pt["cat"] == "体征" and exam) else text
        st, ev = hit(body, pt["pos"], body, pt["neg"])
        rows.append(dict(pt=pt, st=st, ev=ev))
    return dict(d=d, rows=rows)


def st_of(res, kw):
    kw = kw.lower()
    for r in res["rows"]:
        if kw in r["pt"]["label"].lower():
            return r["st"]
    return "missing"


def of(res, st):
    return [r for r in res["rows"] if r["st"] == st]

