def selftest():
    """回归自检：改规则后跑一遍，防止把男性病例又推成妇科病。"""
    fails = []
    cases = {
        "男童腹痛": "性别：男 年龄：12岁\n主诉\n右下腹痛伴呕吐6小时\n体格检查\n腹软，右下腹压痛\n初步诊断\n急性阑尾炎\n",
        "育龄女腹痛": "性别：女 年龄：26岁\n主诉\n右下腹痛12小时\n初步诊断\n急性阑尾炎\n",
    }
    FEM = ("宫外孕", "卵巢", "盆腔炎")
    for name, txt in cases.items():
        ctx = analyze(txt)
        male = ctx["sex"] == "男"
        if male:
            names = [f["name"] for f in framework(ctx)]
            bad = [n for n in names if any(x in n for x in FEM)]
            if bad:
                fails.append("%s：男性病例出现了妇科鉴别 %s" % (name, bad))
            if any(x in report(ctx) for x in ("宫外孕", "卵巢囊肿")):
                fails.append("%s：男性病例报告里出现妇科病名" % name)
        # 报告结构
        rep = report(ctx)
        for sec in ("【一】", "【三】", "【四】", "【九】"):
            if sec not in rep:
                fails.append("%s：报告缺少 %s" % (name, sec))
        if (not MINIMAL_MODE) and "【四】弱提示" in rep and "为什么：" not in rep.split("【四】")[1][:400]:
            fails.append("%s：弱提示没有按「标题/为什么/补写」格式输出" % name)
    # 极简致命核查：卡住的项必须报红；全都有记录时必须放行
    if MINIMAL_MODE:
        bad = analyze("性别：男 年龄：30岁\n主诉\n右下腹痛1天\n体格检查\n右下腹压痛\n初步诊断\n急性阑尾炎\n")
        ids = {x["id"] for x in bad["rules"] if x["lv"] == "red"}
        if "red-lethal" not in ids:
            fails.append("极简模式：缺腹膜刺激征却没有报红")
        ok = analyze("性别：男 年龄：30岁\n主诉\n右下腹痛1天\n体格检查\nT 37.5℃ P 90次/分 BP 120/80mmHg，腹平软，右下腹压痛。\n初步诊断\n急性阑尾炎\n")
        rids = {x["id"] for x in ok["rules"]}
        if "pass-lethal" not in rids:
            fails.append("极简模式：致命项都记录时没有放行")
        if any(x["lv"] == "red" for x in ok["rules"]):
            fails.append("极简模式：已放行的病历不应再有红提醒")
    else:
        for key, txt, want in (
            ("appendicitis", "性别：男 年龄：30岁\n主诉\n右下腹痛1天\n体格检查\n右下腹压痛\n初步诊断\n急性阑尾炎\n", "red-must-appendicitis"),
            ("cholecystitis", "性别：女 年龄：45岁\n主诉\n右上腹痛1天\n初步诊断\n急性胆囊炎\n", "yellow-must-cholecystitis"),
        ):
            r = analyze(txt)["rules"]
            ids = {x["id"] for x in r if x["lv"] == "red"}
            yids = {x["id"] for x in r if x["lv"] == "yellow"}
            if want not in ids and want not in yids:
                fails.append("%s：诊断成立但缺项没被报出（期望 %s）" % (key, want))
    print("自检通过 ✔（男性病例无妇科病名、报告结构完整、极简核查能报警也能放行）" if not fails else "自检失败：")
    for f in fails:
        print("  - " + f)
    return 0 if not fails else 1


