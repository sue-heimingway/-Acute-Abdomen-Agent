EXAM_WORDS = r"(阴囊|睾丸|提睾反射|Prehn|腹股沟|直肠|指检|心肺|双肺|呼吸音|心音)"


def eval_more(ctx):
    out = []
    for m in MORE:
        mech = m["mech"]
        if mech == "妇科" and ctx["sex"] != "女":
            continue
        if mech == "男性" and ctx["sex"] == "女":
            continue
        if mech == "儿科" and not (ctx["age"] is not None and ctx["age"] < 14):
            continue
        mentioned = False
        for p in m["trig"]:
            for mm in re.finditer(p, ctx["full"]):
                if verdict(ctx["full"], mm.start(), mm.end()) != "neg":
                    mentioned = True
                    break
            if mentioned:
                break
        rows = []
        for name, pats in m["checks"]:
            # 查体类项目只在查体段里认；化验/影像仍全篇认
            body = ctx["exam_or_text"] if re.search(EXAM_WORDS, name) else ctx["text"]
            st, ev = hit(body, pats, body)
            rows.append((name, st, ev))
        if not mentioned:
            continue
        out.append(dict(name=m["name"], mech=mech, red=m["red"], tip=m["tip"], rows=rows,
                        missing=[n for n, s, _ in rows if s == "missing"]))
    out.sort(key=lambda r: MECH_ORDER.index(r["mech"]) if r["mech"] in MECH_ORDER else 99)
    return out


def eval_baseline(ctx):
    exempt = bool(re.search(EXEMPT, ctx["full"]))
    sex, age = ctx["sex"], ctx["age"]
    lower = bool(re.search(r"(下腹|右下腹|左下腹|盆腔|全腹|脐周)", ctx["text"]))
    exam = ctx["exam_or_text"]
    out = []
    for label, pat, cond in BASELINE:
        if cond == "female" and sex != "女":
            continue
        if cond == "male" and not (sex == "男" or (age is not None and age < 14)):
            continue
        if cond == "lower" and not lower:
            continue
        ok = bool(re.search(pat, exam))
        out.append(dict(label=label, ok=ok, exempt=exempt and not ok))
    return out


def eval_red(ctx):
    out = []
    for label, ref in RED_LIST:
        if ref in KB:
            r = ctx["res"][ref]
            named = (KB[ref]["name"] in [KB[k]["name"] for k in ctx["main"] if k in KB])
            if not named and not mentions(ctx, ref):
                continue
            miss = [p["pt"]["label"] for p in r["rows"]
                    if p["st"] == "missing" and p["pt"]["core"] and p["pt"]["cat"] in ("实验室", "影像", "处理")]
            out.append(dict(label=label, key=ref, missing=miss))
        else:
            m = next((x for x in ctx["more"] if x["name"] == ref), None)
            if m:
                out.append(dict(label=label, key=ref, missing=m["missing"]))
    return out


