def parse_profile(t):
    sex = age = None
    for p in SEX_RULES:
        m = re.search(p, t)
        if m:
            sex = m.group(1)
            break
    if sex is None and re.search(FEMALE_HINT, t):
        sex = "女"
    m = re.search(r"年龄\s*[:：]?\s*(\d{1,3})", t) or re.search(r"(\d{1,3})\s*(?:岁|周岁)", t)
    if m:
        age = int(m.group(1))
    return sex, age


def resolve(item):
    item = item.strip()
    if not item:
        return None
    for k, d in KB.items():
        if d["name"] in item or SHORT.get(k, d["name"]) in item:
            return k
    for a, c in ALIAS:
        if a in item:
            for k, d in KB.items():
                if d["name"] == c:
                    return k
    for m in MORE:
        if m["name"] in item:
            return "more:" + m["name"]
    return None


def parse_diag(t):
    secs = sections(t)
    diag = ""
    for k in ("初步诊断", "入院诊断", "诊断"):
        if secs.get(k, "").strip():
            diag = secs[k].strip()
            break
    if not diag:
        m = re.search(r"(?:初步诊断|入院诊断|诊断|考虑|拟诊|印象)\s*[:：]?\s*([^\n。;；，,]{2,40})", t)
        if m:
            diag = m.group(1).strip()

    block = secs.get("鉴别诊断", "")
    if not block:
        m = re.search(r"鉴别(?:诊断)?\s*[:：]\s*(.{0,200}?)(?:\n|$)", t, re.S)
        block = m.group(1) if m else ""

    def pieces(s):
        s = re.sub(r"^\s*[:：]?\s*", "", s)
        return [x.strip(" :：-—*") for x in re.split(r"[\n;；,，、。]|(?:\d+[\.、)）])", s)
                if 1 < len(x.strip()) <= 30]

    main, diff = [], []
    for x in pieces(re.sub(r"鉴别诊断.*", "", diag, flags=re.S)) if diag else []:
        k = resolve(x)
        if k and k not in main:
            main.append(k)
    for x in re.split(r"[\n;；。、,，]", block):
        k = resolve(x)
        if k and k not in diff and k not in main:
            diff.append(k)
    diff_count = len([x for x in re.split(r"[\n;；。、,，]", block) if 1 < len(x.strip()) <= 30])
    return main, diff, diff_count

