    a("")
    a("【九】待补充清单")
    todo = ["[强] " + r["item"] for r in red]
    for k in CORE_KEYS:
        r = ctx["res"][k]
        if mentions(ctx, k) or k in ctx["main"]:
            for row in r["rows"]:
                if row["st"] == "missing" and row["pt"]["core"] and row["pt"]["hint"]:
                    todo.append("[要] %s：%s" % (r["d"]["name"], row["pt"]["label"]))
    todo += ["[质控] " + r["item"] for r in yel]
    seen = set()
    for t in todo:
        if t not in seen:
            seen.add(t)
            a("  [ ] " + t)
    if not todo:
        a("  [x] 关键要点已齐备")

    a("")
    a(LINE)
    a("提示：本工具为病历质控辅助，不替代临床判断。")
    a(LINE)
    return "\n".join(L)

