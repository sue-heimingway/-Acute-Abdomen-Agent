def _checks(s):
    out = []
    for part in s.split(";"):
        part = part.strip()
        if not part:
            continue
        name, _, pats = part.partition(":")
        name = name.strip() or pats.strip()
        out.append((name, tuple(p.strip() for p in pats.split("||") if p.strip())))
    return tuple(out)


def MC(name, mech, red, trig, checks, tip=""):
    return dict(name=name, mech=mech, red=bool(red), trig=tuple(trig.split("||")),
                checks=_checks(checks), tip=tip)


