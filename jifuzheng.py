    a("【四】弱提示（黄色：病历质控，不影响急诊决策但会扣分）")
    if MINIMAL_MODE:
        if yel:
            a("  （极简模式下只保留指定的黄牌项，其余质控项不弹）")
        else:
            a("  （极简模式：只防死人与担责的漏洞，质控项不弹提示）")
