    a = L.append
    a(LINE)
    a("急腹症病历核查报告   v%s" % VERSION)
    a(LINE)

    # 零：病因 / 并发症分级预警（单开一栏）
    blk = causes_block(ctx)
    if blk:
        a("")
        L.extend(blk)

    # 一
    a("")
    a("【一】病例解析")
    sex, age = ctx["sex"], ctx["age"]
    tags = []
    if sex == "女" and (age is None or 12 <= age <= 55):
        tags.append("育龄期女性")
    if age is not None and age < 14:
        tags.append("儿童")
    a("  性别：%s    年龄：%s%s" % (sex or "未记录", (str(age) + "岁") if age else "未记录",
                                  ("    " + "  ".join(tags)) if tags else ""))
    secs = sections(ctx["norm"])
    if secs.get("主诉"):
        a("  主诉：" + secs["主诉"].splitlines()[0][:80])
    a("  初步诊断：" + ("、".join(KB[k]["name"] if k in KB else k.replace("more:", "")
                                for k in ctx["main"]) or "未写明"))
    a("  已列鉴别：" + ("、".join(KB[k]["name"] if k in KB else k.replace("more:", "")
                                for k in ctx["diff"]) or "无"))
