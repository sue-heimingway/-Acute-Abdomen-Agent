def _can_print(s, enc):
    try:
        s.encode(enc or "ascii")
        return True
    except Exception:
        return False


# 老式 GBK 控制台打不出 █ ✔ ▶ 这类字符，会自动降级成 ASCII，避免 UnicodeEncodeError
_G = None


def glyphs():
    global _G
    if _G is None:
        force = os.environ.get("JZ_GLYPHS", "").lower()
        if force == "fancy":
            fancy = True
        elif force == "ascii":
            fancy = False
        else:
            fancy = _can_print("█✔✘▶●○×", getattr(sys.stdout, "encoding", None))
        if fancy:
            _G = (("█", "·"), {"pos": "●", "neg": "○", "missing": "×"}, "✔", "✘", "▶")
        else:
            _G = (("#", "."), {"pos": "[+]", "neg": "[-]", "missing": "[ ]"}, "[Y]", "[N]", ">")
    return _G


def analyze(raw):
    norm = normalize(raw)
    text = mask_diag(norm)
    secs = sections(norm)
    sex, age = parse_profile(norm)
    main, diff, diff_count = parse_diag(norm)
    # 查体段：查体项目只能从"体格检查/专科检查"里认，不能拿主诉/既往史说事
    exam = "\n".join(secs.get(k, "") for k in ("体格检查", "专科检查")).strip()
    exam_or_text = exam or text
    res = {k: eval_core(text, d, norm, exam_or_text) for k, d in KB.items()}
    ctx = dict(norm=norm, text=text, full=norm, sex=sex, age=age, main=main,
               diff=diff, diff_count=diff_count, res=res,
               secs=secs, exam=exam, exam_or_text=exam_or_text)
    ctx["more"] = eval_more(ctx)
    ctx["baseline"] = eval_baseline(ctx)
    ctx["red"] = eval_red(ctx)
    ctx["rules"] = build_rules(ctx)
    return ctx


def framework(ctx):
    primary = None
    for k in ctx["main"]:
        if k in KB:
            primary = k
            break
    if primary is None:
        for k in CORE_KEYS:
            if mentions(ctx, k):
                primary = k
                break
    if primary is None:
        return []
    pairs = dict(DIFF.get(primary, []))
    for k, lst in DIFF.items():
        for other, why in lst:
            if other == primary:
                pairs.setdefault(k, "%s常需鉴别本例，共同点：%s" % (KB[k]["name"], why))
    out = []
    male = ctx["sex"] == "男"
    for k in ctx["diff"]:
        if k in KB and k not in [x[0] for x in out] and not (male and k in FEMALE_ONLY):
            out.append((k, pairs.get(k, "与本例初步诊断存在共同临床表现（需写明具体交叉点）"), "已列"))
    for k, why in pairs.items():
        if k in KB and len(out) < 4 and k not in [x[0] for x in out] and not (male and k in FEMALE_ONLY):
            out.append((k, why, "建议补充"))
    rows = []
    for k, why, src in out:
        r = ctx["res"][k]
        rows.append(dict(name=KB[k]["name"], why=why, src=src,
                         sup=[(p["pt"]["label"], p["ev"][0]) for p in of(r, "pos")],
                         ag=[(p["pt"]["label"], p["ev"][0]) for p in of(r, "neg")],
                         pend=[p["pt"]["label"] for p in r["rows"] if p["st"] == "missing" and p["pt"]["core"]]))
    return rows


ALERT_KEYS = ("appendicitis", "cholecystitis", "obstruction", "perforation", "hernia", "ectopic")


def is_acute(ctx):
    """节点一：这份病历像不像急腹症。不像就静默退出。"""
    if any(k in ctx["main"] for k in CORE_KEYS):
        return True
    if any(mentions(ctx, k) for k in CORE_KEYS):
        return True
    if ctx["more"]:
        return True
    # 只要主诉/现病史写了急腹症主诉，就进入节点二（哪怕医生只写“腹痛待查”）
    chief = (ctx["secs"].get("主诉", "") + ctx["secs"].get("现病史", "")) or ctx["full"]
    return bool(re.search(r"(腹痛|肚子痛|腹绞痛|腹胀|呕吐|停止排便|急腹症)", chief))


